@app.route("/api/order", methods=["POST"])
def create_order():
    data = request.json
    items = data.get("items", [])
    note = data.get("note", "")

    if not items:
        return jsonify({"ok": False, "msg": "请至少选择一道菜"})

    with lock:
        order = {
            "id": next_id(),
            "items": items,
            "note": note,
            "status": "pending",
            "time": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "date": datetime.now().strftime("%Y-%m-%d"),
        }
        orders.append(order)
        save_orders(orders)

    return jsonify({"ok": True, "order_id": order["id"]})


